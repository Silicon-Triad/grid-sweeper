"""Display of grid, paths and schedule (spec §7.2 Output Requirements). Owner: Qazi.

Spec: "The integrated program must display:
- The cleaning schedule generated by the CSP solver.
- The sequence of dirty locations visited by the robot.
- The path computed for each journey between locations.
- The final grid showing the completed cleaning task.
- The total number of movements and total navigation cost for the complete
  journey.
- The final status indicating whether all dirty locations were cleaned and
  the robot returned to the charging station."

Spec §6.4: "Display the generated schedule and show that each constraint is
satisfied" (REQ-CSP-19).

All functions return strings; the caller prints them, so tests can compare
text and the notebook output is plain and screenshot-friendly.
"""

from collections.abc import Mapping
from dataclasses import dataclass

from cep.env import Constraints, Grid, Label, Slot, State
from cep.integrate import CHARGER, IntegrationResult

PASS, FAIL = "✓", "✗"

# Grid symbols (display choice). Cleaned cells use lower case "d" so the task
# number stays visible after cleaning.
LEGEND = "Legend: C charger, ## obstacle, Dk dirty, dk cleaned, * path, . free"


@dataclass(frozen=True)
class Check:
    """One constraint checked against a complete assignment (REQ-CSP-19).

    Attributes:
        kind: ``"precedence"``, ``"latest"``, ``"exclusivity"`` or
            ``"assigned"``.
        text: Human-readable evidence, e.g. ``"D1 (T1) before D3 (T3)"``.
        ok: Whether the constraint holds.
    """

    kind: str
    text: str
    ok: bool


def check_schedule(
    assignment: Mapping[Label, Slot], constraints: Constraints
) -> list[Check]:
    """Check every constraint of the problem against an assignment.

    Independent of the solver's own checks, so it is an actual proof that
    the schedule it returned is valid, not a repeat of the same code.

    Args:
        assignment: Label -> slot (complete or not).
        constraints: Scheduling problem.

    Returns:
        One ``Check`` per task-assigned test, per precedence pair, per
        latest-slot limit, plus one for slot exclusivity.
    """
    checks = []
    for v in constraints.variables:
        slot = assignment.get(v)
        ok = slot is not None and 1 <= slot <= constraints.num_slots
        shown = "unassigned" if slot is None else f"T{slot}"
        checks.append(Check("assigned", f"{v} assigned a slot: {shown}", ok))

    for before, after in constraints.precedence:
        b, a = assignment.get(before), assignment.get(after)
        ok = b is not None and a is not None and b < a
        checks.append(
            Check(
                "precedence",
                f"{before} ({_slot(b)}) before {after} ({_slot(a)})",
                ok,
            )
        )

    for task, limit in constraints.latest.items():
        s = assignment.get(task)
        ok = s is not None and s <= limit
        checks.append(Check("latest", f"{task} ≤ T{limit}: {_slot(s)}", ok))

    # Exclusivity: no slot used by two tasks (REQ-CSP-07).
    by_slot: dict[Slot, list[Label]] = {}
    for v, s in assignment.items():
        by_slot.setdefault(s, []).append(v)
    clashes = [
        f"T{s}: {', '.join(vs)}" for s, vs in sorted(by_slot.items()) if len(vs) > 1
    ]
    text = "slot exclusivity: " + (
        "; ".join(clashes) if clashes else "every slot ≤ 1 task"
    )
    checks.append(Check("exclusivity", text, not clashes))
    return checks


def _slot(slot: Slot | None) -> str:
    """Format a slot as ``T<n>``, or ``"-"`` when missing."""
    return "-" if slot is None else f"T{slot}"


def format_schedule(assignment: Mapping[Label, Slot], num_slots: int) -> str:
    """Slot table T1…Tn -> task; empty slots shown as ``-`` (REQ-CSP-19).

    Args:
        assignment: Label -> slot.
        num_slots: Number of available slots.

    Returns:
        Multi-line table text.
    """
    task_in = {s: v for v, s in assignment.items()}
    lines = ["Slot | Task", "-----+-----"]
    for s in range(1, num_slots + 1):
        lines.append(f"{'T' + str(s):<4} | {task_in.get(s, '-')}")
    return "\n".join(lines)


def format_schedule_proof(
    assignment: Mapping[Label, Slot] | None, constraints: Constraints
) -> str:
    """Schedule table plus each constraint with ✓/✗ (spec §6.4, REQ-CSP-19).

    Args:
        assignment: Solver result, or None if no feasible schedule exists.
        constraints: Scheduling problem.

    Returns:
        Text to print.
    """
    if assignment is None:
        return "No feasible schedule: the CSP solver reports failure."
    checks = check_schedule(assignment, constraints)
    lines = [format_schedule(assignment, constraints.num_slots), "", "Constraints:"]
    lines += [f"  {c.text} {PASS if c.ok else FAIL}" for c in checks]
    verdict = "all constraints satisfied" if all(c.ok for c in checks) else "VIOLATED"
    lines.append(f"Result: {verdict}")
    return "\n".join(lines)


def format_grid(
    grid: Grid,
    path: list[State] | None = None,
    cleaned: list[Label] | tuple[Label, ...] = (),
) -> str:
    """Draw the grid as text with row/column numbers (REQ-INT-08).

    Args:
        grid: Environment.
        path: States to mark with ``*`` (stops keep their own symbol).
        cleaned: Labels already cleaned, drawn as ``dk``.

    Returns:
        Multi-line grid text, row 0 at the top.
    """
    cells: dict[State, str] = {}
    for state in path or []:
        cells[state] = "*"
    for cell in grid.obstacles:
        cells[cell] = "##"
    for label, cell in grid.dirty.items():
        cells[cell] = label.lower() if label in cleaned else label
    cells[grid.charger] = "C"

    width = 3
    header = " " * width + "".join(f"{c:>{width}}" for c in range(grid.cols))
    lines = [header]
    for r in range(grid.rows):
        row = "".join(f"{cells.get((r, c), '.'):>{width}}" for c in range(grid.cols))
        lines.append(f"{r:>{width}}{row}")
    return "\n".join(lines)


def _stop(label: str) -> str:
    """Name a stop for display: the charger is shown as ``C``."""
    return "C" if label == CHARGER else label


# "IntegrationResult" is quoted so that this module's code can be placed before
# integrate.py's in the notebook (#27); it is only needed when called.
def format_legs(result: "IntegrationResult") -> str:
    """One block per search call: path, cost, nodes expanded (REQ-INT-08).

    Args:
        result: Integration result.

    Returns:
        Text to print.
    """
    lines = []
    for i, leg in enumerate(result.legs, start=1):
        head = (
            f"Leg {i}: {_stop(leg.source)} {leg.start} -> "
            f"{_stop(leg.target)} {leg.goal}"
        )
        if leg.path is None:
            lines.append(f"{head}: NO PATH (nodes expanded {leg.nodes_expanded})")
        else:
            steps = " -> ".join(str(s) for s in leg.path)
            lines.append(
                f"{head}: cost {leg.cost}, nodes expanded {leg.nodes_expanded}"
            )
            lines.append(f"  {steps}")
    return "\n".join(lines)


def format_result(result: "IntegrationResult", grid: Grid) -> str:
    """Full integration report, in spec §7.2 Output Requirements order.

    Args:
        result: Integration result from ``plan_and_execute``/``run_integration``.
        grid: Environment it ran on.

    Returns:
        Text to print.
    """
    lines = [f"=== Integration ({result.algorithm}) ==="]
    if result.assignment is not None:
        order = [f"T{result.assignment[x]}:{x}" for x in result.schedule]
    else:
        order = list(result.schedule)
    lines.append("Schedule: " + (", ".join(order) if order else "none"))
    visited = ["C"] + result.cleaned + (["C"] if result.success else [])
    lines.append("Visit sequence: " + " -> ".join(visited))
    lines += ["", "Paths:", format_legs(result) or "  (no search run)", ""]
    lines += ["Final grid:", format_grid(grid, result.complete_path, result.cleaned)]
    lines.append(LEGEND)
    moves = len(result.complete_path) - 1
    lines.append(f"Total moves: {moves}, total cost: {result.total_cost}")
    if result.success:
        status = "SUCCESS: all dirty locations cleaned, robot back at charger"
    else:
        left = [x for x in grid.dirty if x not in result.cleaned]
        status = (
            f"FAILURE: {result.reason}; cleaned {result.cleaned or 'none'}, "
            f"not cleaned {left}, robot did not return to charger"
        )
    lines.append("Status: " + status)
    return "\n".join(lines)
